#!/usr/bin/env python3
"""
Generate firmware/path-b-standalone/gen3_stats_tables.h: the Gen 3 base stats,
experience groups and experience curves the standalone firmware needs to turn an
80-byte Gen 3 *box* record (what the Gen 1/2 -> Gen 3 conversion produces) into
the 100-byte *party* record a link trade carries (gen3_party.c), derived from the
pinned PokemonGB_Online_Trades engine's data.

Only species 1..251 are included: those are the only ones a converted Gen 1/2
Pokémon can be, and for them the Gen 3 internal species id equals the Pokédex
number.

Run after scripts/setup.sh (needs third_party/PokemonGB_Online_Trades).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
DATA = os.path.join(REPO_ROOT, "third_party", "PokemonGB_Online_Trades", "useful_data", "rse")
OUT = os.path.join(REPO_ROOT, "firmware", "path-b-standalone", "gen3_stats_tables.h")

LAST_SPECIES = 251
NUM_LEVELS = 100
# stats.bin column order -> the party struct's stat order (HP Atk Def Spe SpA SpD).
FILE_HP, FILE_ATK, FILE_DEF, FILE_SPA, FILE_SPD, FILE_SPE = range(6)
STRUCT_ORDER = (FILE_HP, FILE_ATK, FILE_DEF, FILE_SPE, FILE_SPA, FILE_SPD)


def build():
    if not os.path.isdir(DATA):
        raise SystemExit(f"{DATA} not found — run ./scripts/setup.sh first.")
    with open(os.path.join(DATA, "stats.bin"), "rb") as fh:
        stats = fh.read()
    with open(os.path.join(DATA, "pokemon_exp_groups.bin"), "rb") as fh:
        groups = fh.read()
    with open(os.path.join(DATA, "pokemon_exp.txt"), encoding="utf-8") as fh:
        rows = [ln.split() for ln in fh.read().splitlines() if ln.strip()]
    assert len(rows) == NUM_LEVELS, len(rows)
    num_groups = len(rows[0])
    # curves[group][level-1] = experience needed to BE that level.
    curves = [[int(rows[lv][g]) for lv in range(NUM_LEVELS)] for g in range(num_groups)]
    for c in curves:
        c[0] = 0   # the formulas give -54/1 at level 1 for some curves; level 1 needs 0
        assert all(a < b for a, b in zip(c, c[1:])), "curve not increasing"

    base = [[0] * 6]
    group = [0]
    for sp in range(1, LAST_SPECIES + 1):
        row = stats[sp * 6:sp * 6 + 6]
        base.append([row[i] for i in STRUCT_ORDER])
        assert groups[sp] < num_groups
        group.append(groups[sp])
    return base, group, curves


def render(base, group, curves):
    lines = [
        "// AUTO-GENERATED by tools/gen_gen3_stats.py -- do not edit by hand.",
        "// Gen 3 base stats / experience data for species 1..251, derived from the",
        "// pinned trade engine's data.",
        "#ifndef GEN3_STATS_TABLES_H",
        "#define GEN3_STATS_TABLES_H",
        "#include <stdint.h>",
        "",
        f"#define G3S_LAST_SPECIES {LAST_SPECIES}",
        f"#define G3S_NUM_LEVELS {NUM_LEVELS}",
        f"#define G3S_NUM_EXP_GROUPS {len(curves)}",
        "",
        "// Base stats in party-struct order: HP, Attack, Defense, Speed, Sp. Atk, Sp. Def.",
        "static const uint8_t g3s_base[G3S_LAST_SPECIES + 1][6] = {",
    ]
    for sp, row in enumerate(base):
        lines.append("    {" + ", ".join(f"{v:3d}" for v in row) + f"}},  // {sp}")
    lines += ["};", "", "// Experience group of each species (index into g3s_exp).",
              "static const uint8_t g3s_exp_group[G3S_LAST_SPECIES + 1] = {"]
    for i in range(0, len(group), 16):
        lines.append("    " + ", ".join(str(v) for v in group[i:i + 16]) + ",")
    lines += ["};", "", "// g3s_exp[group][level - 1] = total experience needed to be that level.",
              "static const uint32_t g3s_exp[G3S_NUM_EXP_GROUPS][G3S_NUM_LEVELS] = {"]
    for c in curves:
        lines.append("    {")
        for i in range(0, len(c), 10):
            lines.append("        " + ", ".join(str(v) for v in c[i:i + 10]) + ",")
        lines.append("    },")
    lines += ["};", "", "#endif // GEN3_STATS_TABLES_H"]
    return "\n".join(lines) + "\n"


def main():
    text = render(*build())
    if "--check" in sys.argv[1:]:
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() != text:
                print(f"{OUT} is stale — re-run tools/gen_gen3_stats.py", file=sys.stderr)
                return 1
        print(f"{OUT} is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
