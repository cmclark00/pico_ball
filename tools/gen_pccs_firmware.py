#!/usr/bin/env python3
"""
Prepare the Pokemon Community Conversion Standard (third_party/PCCS) for the
standalone firmware's on-device Gen 1/2 -> Gen 3 conversion.

PCCS loads its data tables from binary blobs that its own build embeds with
devkitPro's bin2s. The firmware build has no bin2s, so this writes the same
symbols as plain C into firmware/path-b-standalone/pccs_gen/ (gitignored, like
the other generated-from-third_party sources):

    pccs_tables.c        the table bytes
    <TABLE>_bin.h        the extern declarations PCCS's pokemon_data.cpp includes

The firmware's CMakeLists compiles PCCS in when pccs_gen/pccs_tables.c exists and
falls back to a stub (conversion reported as unavailable) when it does not.

Needs third_party/PCCS/data/*.bin, produced by PCCS's table generator — run
scripts/setup.sh (tools/build_pccs.sh) first. Exits 0 without writing anything
if PCCS or its tables are missing, so builds without PCCS keep working.
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
PCCS_DATA = os.path.join(REPO_ROOT, "third_party", "PCCS", "data")
OUT_DIR = os.path.join(REPO_ROOT, "firmware", "path-b-standalone", "pccs_gen")

# The tables PCCS's host (non-GBA) path links against.
TABLES = [
    "EXP_GROUPS", "GENDER_RATIO", "NUM_ABILITIES", "FIRST_MOVES", "POWER_POINTS",
    "EVENT_PKMN", "TYPES", "gen_1_charsets", "gen_2_charsets", "gen_3_charsets",
]


def main():
    missing = [t for t in TABLES if not os.path.isfile(os.path.join(PCCS_DATA, t + ".bin"))]
    if missing:
        if os.path.isdir(OUT_DIR):
            shutil.rmtree(OUT_DIR)   # never leave tables from an older PCCS behind
        print(f"PCCS tables not found in {PCCS_DATA} (missing {missing[0]}.bin, ...): "
              "firmware will build WITHOUT on-device Gen 1/2 -> Gen 3 conversion.")
        return 0

    os.makedirs(OUT_DIR, exist_ok=True)
    src = [
        "// AUTO-GENERATED by tools/gen_pccs_firmware.py -- do not edit, do not commit.",
        "// PCCS data tables (third_party/PCCS/data/*.bin) as C arrays.",
        "#include <stdint.h>",
        "",
    ]
    total = 0
    for name in TABLES:
        with open(os.path.join(PCCS_DATA, name + ".bin"), "rb") as fh:
            data = fh.read()
        total += len(data)
        with open(os.path.join(OUT_DIR, f"{name}_bin.h"), "w", newline="\n") as fh:
            fh.write(
                "// AUTO-GENERATED by tools/gen_pccs_firmware.py -- do not edit.\n"
                f"#ifndef PCCS_GEN_{name.upper()}_BIN_H\n"
                f"#define PCCS_GEN_{name.upper()}_BIN_H\n"
                "#include <stdint.h>\n#include <stddef.h>\n"
                "#ifdef __cplusplus\nextern \"C\" {\n#endif\n"
                f"extern const uint8_t {name}_bin[];\n"
                "#ifdef __cplusplus\n}\n#endif\n"
                f"#define {name}_bin_size ((size_t){len(data)})\n"
                "#endif\n")
        # 4-byte alignment, as PCCS's own bin2s step uses (the charsets are read as u16).
        src.append(f"_Alignas(4) const uint8_t {name}_bin[{len(data)}] = {{")
        for i in range(0, len(data), 16):
            src.append("    " + ",".join(str(b) for b in data[i:i + 16]) + ",")
        src.append("};")
        src.append("")
    with open(os.path.join(OUT_DIR, "pccs_tables.c"), "w", newline="\n") as fh:
        fh.write("\n".join(src))
    print(f"Wrote {OUT_DIR} ({len(TABLES)} tables, {total} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
