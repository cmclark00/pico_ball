#!/usr/bin/env python3
"""
Generate firmware/path-b-standalone/cross_gen_tables.h: the lookup tables the
standalone firmware needs to convert a stored Pokémon between Gen 1 and Gen 2
(cross_gen.c), derived from the pinned PokemonGB_Online_Trades engine's data so
they can't drift from the tables the rest of the project decodes with.

  xg_g1_to_dex[256]   Gen 1 internal species index -> Pokédex number (0 = none)
  xg_dex_to_g1[152]   Pokédex number (1..151) -> Gen 1 internal species index
  xg_g1_types[152][2] Gen 1 type bytes, by Pokédex number
  xg_g1_special[152]  Gen 1 base Special, by Pokédex number
  xg_g2_spatk[152]    Gen 2 base Sp. Atk, by Pokédex number
  xg_g2_spdef[152]    Gen 2 base Sp. Def, by Pokédex number

Gen 2 species ids ARE Pokédex numbers; Gen 1's are the scrambled internal index
(Rhydon = 0x01, Bulbasaur = 0x99, ...). Only Special differs between the two
generations' base stats (asserted below), so that is the only stat cross_gen.c
has to recompute.

Run after scripts/setup.sh (needs third_party/PokemonGB_Online_Trades).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
DATA = os.path.join(REPO_ROOT, "third_party", "PokemonGB_Online_Trades", "useful_data")
OUT = os.path.join(REPO_ROOT, "firmware", "path-b-standalone", "cross_gen_tables.h")

NUM_DEX = 151
# Column order inside the engine's stats.bin files.
RBY_HP, RBY_ATK, RBY_DEF, RBY_SPD, RBY_SPC = range(5)
GSC_HP, GSC_ATK, GSC_DEF, GSC_SPA, GSC_SPDEF, GSC_SPD = range(6)


def _read(*parts):
    with open(os.path.join(DATA, *parts), "rb") as fh:
        return fh.read()


def _names(folder):
    text = _read(folder, "pokemon_names.txt").decode("utf-8")
    return text.splitlines()[:256]   # splitlines: tolerate a CRLF checkout


def build():
    if not os.path.isdir(DATA):
        raise SystemExit(f"{DATA} not found — run ./scripts/setup.sh first.")

    rby_names, gsc_names = _names("rby"), _names("gsc")
    rby_stats, gsc_stats = _read("rby", "stats.bin"), _read("gsc", "stats.bin")
    rby_types = _read("rby", "types.bin")
    assert len(rby_stats) == 256 * 5 and len(gsc_stats) == 256 * 6
    assert len(rby_types) == 256 * 2

    dex_of_name = {gsc_names[d]: d for d in range(1, NUM_DEX + 1)}
    assert len(dex_of_name) == NUM_DEX

    g1_to_dex = [0] * 256
    dex_to_g1 = [0] * (NUM_DEX + 1)
    for idx in range(1, 256):
        dex = dex_of_name.get(rby_names[idx])
        if dex is None:
            continue  # MissingNo. and other non-Pokémon slots
        assert dex_to_g1[dex] == 0, f"duplicate Gen 1 index for {rby_names[idx]}"
        g1_to_dex[idx] = dex
        dex_to_g1[dex] = idx
    assert all(dex_to_g1[d] for d in range(1, NUM_DEX + 1)), "unmapped species"

    types = [(0, 0)] * (NUM_DEX + 1)
    special = [0] * (NUM_DEX + 1)
    spatk = [0] * (NUM_DEX + 1)
    spdef = [0] * (NUM_DEX + 1)
    for dex in range(1, NUM_DEX + 1):
        idx = dex_to_g1[dex]
        r = rby_stats[idx * 5:idx * 5 + 5]
        g = gsc_stats[dex * 6:dex * 6 + 6]
        # HP / Attack / Defense / Speed are identical in both generations, so a
        # conversion only ever has to recompute the Special-derived stats.
        same = ((r[RBY_HP], r[RBY_ATK], r[RBY_DEF], r[RBY_SPD]) ==
                (g[GSC_HP], g[GSC_ATK], g[GSC_DEF], g[GSC_SPD]))
        assert same, f"non-Special base stat differs for {gsc_names[dex]}"
        types[dex] = (rby_types[idx * 2], rby_types[idx * 2 + 1])
        special[dex] = r[RBY_SPC]
        spatk[dex] = g[GSC_SPA]
        spdef[dex] = g[GSC_SPDEF]

    return {
        "g1_to_dex": g1_to_dex, "dex_to_g1": dex_to_g1, "types": types,
        "special": special, "spatk": spatk, "spdef": spdef, "names": gsc_names,
    }


def _rows(values, per_row, fmt):
    out = []
    for i in range(0, len(values), per_row):
        out.append("    " + ", ".join(fmt(v) for v in values[i:i + per_row]) + ",")
    return out


def render(t):
    dec = lambda v: f"{v:3d}"      # noqa: E731
    hx = lambda v: f"0x{v:02X}"    # noqa: E731
    lines = [
        "// AUTO-GENERATED by tools/gen_cross_gen.py -- do not edit by hand.",
        "// Gen 1 <-> Gen 2 conversion tables, derived from the pinned trade",
        "// engine's species names, types and base stats.",
        "#ifndef CROSS_GEN_TABLES_H",
        "#define CROSS_GEN_TABLES_H",
        "#include <stdint.h>",
        "",
        f"#define XG_NUM_DEX {NUM_DEX}",
        "",
        "// Gen 1 internal species index -> Pokédex number (0 = not a Pokémon).",
        "static const uint8_t xg_g1_to_dex[256] = {",
        *_rows(t["g1_to_dex"], 16, dec),
        "};",
        "",
        "// Pokédex number (1..151) -> Gen 1 internal species index.",
        "static const uint8_t xg_dex_to_g1[XG_NUM_DEX + 1] = {",
        *_rows(t["dex_to_g1"], 8, hx),
        "};",
        "",
        "// Gen 1 type bytes {type1, type2}, by Pokédex number.",
        "static const uint8_t xg_g1_types[XG_NUM_DEX + 1][2] = {",
    ]
    for dex, (a, b) in enumerate(t["types"]):
        name = t["names"][dex] if dex else "(none)"
        lines.append(f"    {{0x{a:02X}, 0x{b:02X}}},  // {dex:3d} {name}")
    lines += [
        "};",
        "",
        "// Gen 1 base Special, by Pokédex number.",
        "static const uint8_t xg_g1_special[XG_NUM_DEX + 1] = {",
        *_rows(t["special"], 16, dec),
        "};",
        "",
        "// Gen 2 base Sp. Atk, by Pokédex number.",
        "static const uint8_t xg_g2_spatk[XG_NUM_DEX + 1] = {",
        *_rows(t["spatk"], 16, dec),
        "};",
        "",
        "// Gen 2 base Sp. Def, by Pokédex number.",
        "static const uint8_t xg_g2_spdef[XG_NUM_DEX + 1] = {",
        *_rows(t["spdef"], 16, dec),
        "};",
        "",
        "#endif // CROSS_GEN_TABLES_H",
    ]
    return "\n".join(lines) + "\n"


def main():
    text = render(build())
    if "--check" in sys.argv[1:]:
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() != text:
                print(f"{OUT} is stale — re-run tools/gen_cross_gen.py", file=sys.stderr)
                return 1
        print(f"{OUT} is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
