bool conv_g1_to_g2_rec(const uint8_t *g1, uint8_t *g2) {
    uint8_t g2_species = g1_to_g2[g1[0x00]];
    if (!g2_species) return false;
    memset(g2, 0, 70);
    g2[0x00] = g2_species;
    // item: 0 (none)
    g2[0x02] = g1[0x08]; g2[0x03] = g1[0x09]; // moves
    g2[0x04] = g1[0x0A]; g2[0x05] = g1[0x0B];
    g2[0x06] = g1[0x0C]; g2[0x07] = g1[0x0D]; // OT ID
    g2[0x08] = g1[0x0E]; g2[0x09] = g1[0x0F]; // EXP
    g2[0x0A] = g1[0x10];
    g2[0x0B] = g1[0x11]; g2[0x0C] = g1[0x12]; // HP EV
    g2[0x0D] = g1[0x13]; g2[0x0E] = g1[0x14]; // ATK EV
    g2[0x0F] = g1[0x15]; g2[0x10] = g1[0x16]; // DEF EV
    g2[0x11] = g1[0x17]; g2[0x12] = g1[0x18]; // SPD EV
    g2[0x13] = g1[0x19]; g2[0x14] = g1[0x1A]; // SpAtk EV = SPC EV
    g2[0x15] = g1[0x1B]; g2[0x16] = g1[0x1C]; // DVs
    g2[0x17] = g1[0x1D] & 0x3F; g2[0x18] = g1[0x1E] & 0x3F; // PP
    g2[0x19] = g1[0x1F] & 0x3F; g2[0x1A] = g1[0x20] & 0x3F;
    g2[0x1B] = 70;   // happiness default
    g2[0x1C] = 0;    // no Pokérus
    g2[0x1D] = 0; g2[0x1E] = 0; // caught data
    g2[0x1F] = g1[0x21]; // level
    g2[0x20] = g1[0x04]; // status
    // g2[0x21] = 0 (unused)
    g2[0x22] = g1[0x01]; g2[0x23] = g1[0x02]; // current HP
    g2[0x24] = g1[0x22]; g2[0x25] = g1[0x23]; // max HP
    g2[0x26] = g1[0x24]; g2[0x27] = g1[0x25]; // ATK
    g2[0x28] = g1[0x26]; g2[0x29] = g1[0x27]; // DEF
    g2[0x2A] = g1[0x28]; g2[0x2B] = g1[0x29]; // SPD
    g2[0x2C] = g1[0x2A]; g2[0x2D] = g1[0x2B]; // SpAtk = SPC
    g2[0x2E] = g1[0x2A]; g2[0x2F] = g1[0x2B]; // SpDef = SPC
    memcpy(g2 + 0x30, g1 + 0x2C, 11); // OT name
    memcpy(g2 + 0x3B, g1 + 0x37, 11); // nickname
    return true;
}

bool conv_g2_to_g1_rec(const uint8_t *g2, uint8_t *g1) {
    if (g2[0x00] < 1 || g2[0x00] > 151) return false;
    uint8_t g1s = g2_to_g1[g2[0x00]];
    if (!g1s) return false;
    memset(g1, 0, 66);
    g1[0x00] = g1s;
    g1[0x01] = g2[0x22]; g1[0x02] = g2[0x23]; // current HP
    g1[0x03] = g2[0x1F]; // level_box
    g1[0x04] = g2[0x20]; // status
    g1[0x05] = g1_types[g1s][0]; // type1
    g1[0x06] = g1_types[g1s][1]; // type2
    g1[0x07] = 0;        // catch_rate (0 = compatible default)
    // moves: zero Gen 2-exclusive moves (index > 165)
    for (int i = 0; i < 4; i++) {
        uint8_t mv = g2[0x02 + i];
        g1[0x08 + i] = (mv > 165) ? 0 : mv;
    }
    g1[0x0C] = g2[0x06]; g1[0x0D] = g2[0x07]; // OT ID
    g1[0x0E] = g2[0x08]; g1[0x0F] = g2[0x09]; // EXP
    g1[0x10] = g2[0x0A];
    g1[0x11] = g2[0x0B]; g1[0x12] = g2[0x0C]; // HP EV
    g1[0x13] = g2[0x0D]; g1[0x14] = g2[0x0E]; // ATK EV
    g1[0x15] = g2[0x0F]; g1[0x16] = g2[0x10]; // DEF EV
    g1[0x17] = g2[0x11]; g1[0x18] = g2[0x12]; // SPD EV
    g1[0x19] = g2[0x13]; g1[0x1A] = g2[0x14]; // SPC EV = SpAtk EV
    g1[0x1B] = g2[0x15]; g1[0x1C] = g2[0x16]; // DVs
    // PP: zero for any move we zeroed above
    for (int i = 0; i < 4; i++)
        g1[0x1D + i] = g1[0x08 + i] ? (g2[0x17 + i] & 0x3F) : 0;
    g1[0x21] = g2[0x1F]; // level
    g1[0x22] = g2[0x24]; g1[0x23] = g2[0x25]; // max HP
    g1[0x24] = g2[0x26]; g1[0x25] = g2[0x27]; // ATK
    g1[0x26] = g2[0x28]; g1[0x27] = g2[0x29]; // DEF
    g1[0x28] = g2[0x2A]; g1[0x29] = g2[0x2B]; // SPD
    g1[0x2A] = g2[0x2C]; g1[0x2B] = g2[0x2D]; // SPC = SpAtk
    memcpy(g1 + 0x2C, g2 + 0x30, 11); // OT name
    memcpy(g1 + 0x37, g2 + 0x3B, 11); // nickname
    return true;
}
